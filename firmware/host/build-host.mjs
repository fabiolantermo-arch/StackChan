// BUILD ONLY. Compiles the Moddable host for the M5StackChan with Robottino's
// partition table. Deliberately offers no flash/deploy option.
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {existsSync,readFileSync,readdirSync,mkdirSync,copyFileSync,writeFileSync,unlinkSync,utimesSync} from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
const root=fileURLToPath(new URL('../../',import.meta.url));
const work=path.join(root,'work');
const upstream=path.join(work,'stack-chan-upstream');
const sdk=path.join(work,'moddable-sdk-10.1.0');
const idf=path.join(work,'esp-idf-v6.1');
const expected='906ee9a0cd2a0107a24c714efb10274f3b546afa';
const revision=spawnSync('git',['rev-parse','HEAD'],{cwd:upstream,encoding:'utf8'});
if(revision.status!==0||revision.stdout.trim()!==expected)throw Error('Upstream revision differs from the documented baseline.');
// Robottino's own changes to the host sources live in firmware/host/patches/ (in git; work/ is not): *.patch for the
// Stack-chan checkout, moddable/*.patch for the Moddable SDK. Each one is applied if it is not there yet, and nothing
// else may differ from the baseline of either checkout.
const patchInfo={};
const applyPatches=(checkout,patchDir,label)=>{
  const git=(...args)=>spawnSync('git',args,{cwd:checkout,encoding:'utf8'});
  const names=existsSync(patchDir)?readdirSync(patchDir).filter(f=>f.endsWith('.patch')).sort():[],patched=new Set();
  for(const name of names){
    const file=path.join(patchDir,name);
    if(git('apply','--reverse','--check',file).status!==0){
      const applied=git('apply',file);if(applied.status!==0)throw Error(`Patch ${label}${name} does not apply: ${applied.stderr}`);
    }
    for(const line of git('apply','--numstat',file).stdout.split('\n')){const f=line.split('\t')[2];if(f)patched.add(f);}
    patchInfo[label+name]=createHash('sha256').update(readFileSync(file)).digest('hex');
  }
  const changed=git('diff','--name-only').stdout.split('\n').filter(Boolean);
  const stray=changed.filter(f=>!patched.has(f)),missing=[...patched].filter(f=>!changed.includes(f));
  if(stray.length||missing.length)throw Error(`${checkout} differs from baseline plus patches: ${JSON.stringify({stray,missing})}`);
};
applyPatches(upstream,path.join(root,'firmware/host/patches'),'');
applyPatches(sdk,path.join(root,'firmware/host/patches/moddable'),'moddable/');
if(readFileSync(path.join(sdk,'tools/VERSION'),'utf8').trim()!=='10.1.0')throw Error('Moddable SDK 10.1.0 required in work/moddable-sdk-10.1.0.');
for(const p of [path.join(sdk,'build/bin/mac/release/mcconfig'),path.join(idf,'export.sh'),path.join(work,'fontbm/build/fontbm')])if(!existsSync(p))throw Error(`Missing tool: ${p}`);
const env={...process.env,IDF_TOOLS_PATH:path.join(work,'espressif-tools'),IDF_PATH:idf,MODDABLE:sdk,FONTBM:path.join(work,'fontbm/build/fontbm')};
delete env.UPLOAD_PORT;
// Upstream resolves some resource paths relative to the main manifest, so the
// small overlay is written next to the upstream host manifest only for the build.
// SDKCONFIGPATH: the Moddable board manifest would otherwise override the Stack-chan
// sdkconfig generated by upstream (version descriptor and audio settings).
const manifest=path.join(upstream,'firmware/host/app/manifest_robottino_cores3.json');
const override=path.join(upstream,'firmware/host/app/manifest_robottino_override.json');
// Send memory of every TCP connection. Moddable's default is 5744 bytes (four packets of 1436): a connection holds
// that much and takes more only when the network has confirmed it, so on the iPhone hotspot (130-190 ms for a round
// trip) nothing left the robot faster than about 23 KB/s (measured on 10 Nov 2026). Twice as much here: the memory
// is used only by data on its way, and it is the robot's internal memory, which is short while the camera is on.
// The receive window (CONFIG_LWIP_TCP_WND_DEFAULT) stays as it is: one change at a time. Manifest esp32Config is
// merged over the SDK defaults; the Stack-chan sdkconfig, merged last, has no network setting.
const TCP_SEND_BUFFER=8*1436;
// Native stack of the main task, where XS runs (11 Nov 2026): Moddable's default is 10 KB (lib/main/main.c kStack),
// of which XS keeps 1 KB as its limit. At 14:23:19 the robot stopped with «XS abort status=9» (native stack overflow,
// fxCheckCStack) while the garbage collector was marking objects recursively through the Piu screen tree
// (PiuContainerMark, PiuContentMark, PiuDieMark): the restarts with nothing on the log came from there. 16 KB, 6 KB
// more of internal memory.
const NATIVE_STACK=16*1024;
// Included last, as upstream's own release wrapper does, so these values win.
writeFileSync(override,JSON.stringify({build:{PARTITIONS_FILE:path.join(root,'firmware/host/partitions.csv'),SDKCONFIGPATH:path.join(upstream,'firmware/dist/generated/sdkconfig/m5stackchan_cores3')},creation:{nativeStack:NATIVE_STACK},esp32Config:{CONFIG_LWIP_TCP_SND_BUF_DEFAULT:String(TCP_SEND_BUFFER)}},null,2)+'\n');
writeFileSync(manifest,JSON.stringify({include:['./manifest_m5stackchan_cores3.json','./manifest_robottino_override.json']},null,2)+'\n');
process.on('exit',()=>{for(const f of [manifest,override])try{unlinkSync(f);}catch{}});
// Moddable's makefile copies its project template over the build's project folder whenever the template folder has a
// later date, and a folder's date can change with nothing in it changed. The copy lands after mcconfig has written our
// partition table and puts Moddable's own back (4 MB, no room for the MOD): the build of 10 Nov 2026 failed that way.
// Giving the build's folder today's date keeps our table; the check on the built table below remains the real guard.
const project=path.join(upstream,'firmware/dist/tmp/esp32/m5stackchan_cores3/release/stack-chan-host/xsProj-esp32s3');
if(existsSync(project)){const now=new Date();utimesSync(project,now,now);}
const cmd=`. "${idf}/export.sh" >/dev/null && export PATH="${sdk}/build/bin/mac/release:$PATH" && npm run build:m5stackchan_cores3 -- --manifest "${manifest}"`;
const result=spawnSync('bash',['-c',cmd],{cwd:path.join(upstream,'firmware'),stdio:'inherit',env});
if(result.status!==0)process.exit(result.status??1);
const out=path.join(upstream,'firmware/dist/bin/esp32/m5stackchan_cores3/release/stack-chan-host');
const parts=readFileSync(path.join(out,'partition-table.bin'));
const table=[];for(let i=0;i<parts.length;i+=32){if(parts[i]!==0xaa||parts[i+1]!==0x50)break;table.push({name:parts.subarray(i+12,i+28).toString().replace(/\0.*$/s,''),type:parts[i+2],subtype:parts[i+3],offset:parts.readUInt32LE(i+4),size:parts.readUInt32LE(i+8)});}
const factory=table.find(p=>p.name==='factory'),xs=table.find(p=>p.name==='xs');
const app=readFileSync(path.join(out,'xs_esp32.bin'));
const version=app.subarray(0x30,0x50).toString().replace(/\0.*$/s,'');
if(version!=='10.1.0+stackchan.2')throw Error(`Unexpected firmware descriptor version: ${version}`);
if(!factory||!xs||xs.size!==0x600000||factory.size!==0x900000)throw Error(`Unexpected partition table: ${JSON.stringify(table)}`);
if(app.length>factory.size)throw Error(`Host ${app.length} exceeds factory ${factory.size}`);
// What ESP-IDF really built with: the setting must have arrived, and the receive window must be the usual one.
const sdkconfig=readFileSync(path.join(project,'sdkconfig'),'utf8');
const setting=name=>sdkconfig.match(new RegExp(`^${name}=(.*)$`,'m'))?.[1];
const network={tcpSendBuffer:Number(setting('CONFIG_LWIP_TCP_SND_BUF_DEFAULT')),tcpReceiveWindow:Number(setting('CONFIG_LWIP_TCP_WND_DEFAULT')),tcpPacket:Number(setting('CONFIG_LWIP_TCP_MSS'))};
if(network.tcpSendBuffer!==TCP_SEND_BUFFER||network.tcpReceiveWindow!==5744||network.tcpPacket!==1436)throw Error(`Unexpected network settings: ${JSON.stringify(network)}`);
// The native stack must have reached the XS creation the host starts with (last number of the creation in mc.xs.c).
const creation=readFileSync(path.join(project,'..','mc.xs.c'),'utf8').match(/\{ (\d+(?:, \d+){12})\},\n\t"main"/)?.[1]?.split(', ').map(Number);
if(creation?.at(-1)!==NATIVE_STACK)throw Error(`Unexpected native stack: ${JSON.stringify(creation)}`);
const dest=path.join(root,'firmware/artifacts/host');mkdirSync(dest,{recursive:true});
const files={};for(const f of ['bootloader.bin','partition-table.bin','xs_esp32.bin']){copyFileSync(path.join(out,f),path.join(dest,f));files[f]=createHash('sha256').update(readFileSync(path.join(out,f))).digest('hex');}
writeFileSync(path.join(dest,'build-info.json'),JSON.stringify({builtAt:new Date().toISOString(),stackchanCommit:expected,patches:patchInfo,moddableVersion:'10.1.0',espIdf:'v6.1',target:'m5stackchan_cores3',partitions:table.map(p=>({...p,offset:'0x'+p.offset.toString(16),size:'0x'+p.size.toString(16)})),hostBytes:app.length,network,nativeStack:NATIVE_STACK,flashed:false,sha256:files},null,2)+'\n');
console.log(`Host ${app.length} bytes in factory 0x${factory.size.toString(16)}; xs 0x${xs.size.toString(16)} at 0x${xs.offset.toString(16)}; TCP send buffer ${network.tcpSendBuffer}; native stack ${NATIVE_STACK}. Not flashed.`);
