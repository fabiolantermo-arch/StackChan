// Makes a spoken phrase for the MOD out of a recording: assets/<name>.bin, WAV PCM16 mono 16 kHz with the plain
// 44-byte header (same format as the laugh), the silence at the two ends cut away, peak at -1 dBFS.
// Usage: node firmware/stackchan-mod/prepare-phrase.mjs <recording.wav> <name>
//        node firmware/stackchan-mod/prepare-phrase.mjs --mouths      (only writes phrase-mouths.js again)
// It also writes phrase-mouths.js: how open the mouth is, every 50 ms, while each phrase of motion-sense.js is said
// (owner, 14 Nov 2026: «deve anche muovere la bocca mentre dice le frasi»).
//
// The recordings of 14 Nov 2026 (ehi-piano, dove-mi-porti: what Robottino says when it is shaken or lifted) are
// Robottino's own voice (ElevenLabs, Sami), taken from a test conversation on the app's route, where the reply is
// saved as work/virtual-robot/reply.wav:
//   ROBOTTINO_SESSION=frase-1 npm run robot:talk -- --app --elevenlabs "Fai finta che qualcuno ti stia scuotendo forte. Rispondi solo con queste parole: Hei! Piano, piano!"
//   ROBOTTINO_SESSION=frase-2 npm run robot:talk -- --app --elevenlabs "Fai finta che qualcuno ti sollevi e ti porti via. Rispondi solo con queste parole: Hei! Dove mi porti?"
// («Hei»: the Mac's voice saying «Ehi» was recognized as «Eh».) A new session name each time, or the agent remembers
// the phrase before. The log says what was really said: check it before keeping the file. Each run is one of the
// day's conversations.
// Waking up (14 Nov 2026, wake-up.js): «Ciao, eccomi!» and a yawn, the same way (the yawn's mouth is wake-up.js's own):
//   ROBOTTINO_SESSION=risveglio-ciao-1 npm run robot:talk -- --app --elevenlabs "Ti sei appena svegliato e saluti con allegria. Rispondi solo con queste parole: Ciao, eccomi!"
//   ROBOTTINO_SESSION=risveglio-sbadiglio-2 npm run robot:talk -- --app --elevenlabs "Ti sei appena svegliato e fai uno sbadiglio lungo e assonnato. Rispondi solo con questo suono, senza altre parole: Uaaaaaaaaah... mmh."
//   (said: «Uaaa, mmh»; the first try, «Aaaaahm», was too short to be a yawn)
import {spawnSync} from 'node:child_process';
import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {HELD_PHRASES,SHAKEN_PHRASES,FALLEN_PHRASES} from './motion-sense.js';
import {WAKE_HELLO} from './wake-up.js';
import {HAND_SOUNDS} from './live-wire.js';
export const MOUTH_STEP_MS=50;
// How open the mouth is in each step of the recording: 0 closed … 4 wide open (portrait-state.js MOUTH_POSES), from
// how loud that step is. The recordings all peak at -1 dBFS, so the same thresholds fit every one of them.
export function mouthTrack(samples,rate=16000){
  const step=rate*MOUTH_STEP_MS/1000;let track='';
  for(let at=0;at<samples.length;at+=step){
    let energy=0,count=0;for(let i=at;i<Math.min(samples.length,at+step);i++){energy+=samples[i]*samples[i];count++;}
    const loud=Math.sqrt(energy/Math.max(1,count));track+=loud<350?0:loud<1000?1:loud<2200?2:loud<4000?3:4;
  }
  return track.replace(/0+$/,'')+'0';
}
// The samples of a prepared phrase (assets/<file>: plain 44-byte header, PCM16).
export const phraseSamples=bytes=>new Int16Array(bytes.buffer.slice(bytes.byteOffset+44,bytes.byteOffset+44+((bytes.length-44)&~1)));
export async function mouthsModule(){
  const lines=[];
  for(const [file] of [...HELD_PHRASES,...SHAKEN_PHRASES,...FALLEN_PHRASES,[WAKE_HELLO],[HAND_SOUNDS.thumbsDown]])lines.push(`  '${file}':'${mouthTrack(phraseSamples(await readFile(new URL('./assets/'+file,import.meta.url))))}'`);
  return `// GENERATED by prepare-phrase.mjs from the recordings in assets/. Do not edit: run it again instead.\n// How open the mouth is while Robottino says each of its recorded phrases (motion-sense.js): one digit for every\n// PHRASE_MOUTH_MS of the recording, 0 closed … 4 wide open (portrait-state.js MOUTH_POSES).\nexport const PHRASE_MOUTH_MS=${MOUTH_STEP_MS};\nexport const PHRASE_MOUTHS={\n${lines.join(',\n')}\n};\n`;
}
if(import.meta.url===pathToFileURL(process.argv[1]??'').href){
const [source,name]=process.argv.slice(2);
if(source!=='--mouths'){
if(!source||!/^[a-z0-9-]{1,40}$/.test(name??''))throw Error('usage: node prepare-phrase.mjs <recording.wav> <name of lowercase letters, digits and dashes>');
const rate=16000,raw=spawnSync('ffmpeg',['-loglevel','error','-i',source,'-ac','1','-ar',String(rate),'-f','s16le','pipe:1'],{maxBuffer:50e6});
if(raw.status!==0)throw Error('ffmpeg: '+raw.stderr);
const all=new Int16Array(raw.stdout.buffer,raw.stdout.byteOffset,raw.stdout.length>>1);
// Silence: under 1% of full scale. 30 ms are left before the first sound and 120 ms after the last.
let first=0,last=all.length-1;const quiet=328;
while(first<all.length&&Math.abs(all[first])<quiet)first++;
while(last>first&&Math.abs(all[last])<quiet)last--;
if(first>=last)throw Error('the recording is silent');
const from=Math.max(0,first-rate*.03),to=Math.min(all.length,last+rate*.12),samples=all.subarray(Math.floor(from),Math.floor(to));
let peak=0;for(const v of samples)peak=Math.max(peak,Math.abs(v));
const gain=32767*10**(-1/20)/peak,data=Buffer.alloc(samples.length*2);
samples.forEach((v,i)=>data.writeInt16LE(Math.max(-32768,Math.min(32767,Math.round(v*gain))),i*2));
// A short fade at the two ends, so that the cut makes no click.
for(let i=0,n=Math.min(160,samples.length>>1);i<n;i++){for(const at of [i,samples.length-1-i])data.writeInt16LE(Math.round(data.readInt16LE(at*2)*i/n),at*2);}
const header=Buffer.alloc(44);
header.write('RIFF',0);header.writeUInt32LE(36+data.length,4);header.write('WAVEfmt ',8);header.writeUInt32LE(16,16);header.writeUInt16LE(1,20);header.writeUInt16LE(1,22);
header.writeUInt32LE(rate,24);header.writeUInt32LE(rate*2,28);header.writeUInt16LE(2,32);header.writeUInt16LE(16,34);header.write('data',36);header.writeUInt32LE(data.length,40);
await writeFile(new URL(`./assets/${name}.bin`,import.meta.url),Buffer.concat([header,data]));
console.log(`assets/${name}.bin: ${(samples.length/rate).toFixed(2)} s, gain ${(20*Math.log10(gain)).toFixed(1)} dB, ${44+data.length} bytes`);
}
await writeFile(new URL('./phrase-mouths.js',import.meta.url),await mouthsModule());
console.log('phrase-mouths.js written');
}
